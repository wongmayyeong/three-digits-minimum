import { NextResponse } from 'next/server';
import { createEpisode } from '@/lib/debate/refresh';
import { createSnapshot } from '@/lib/debate/snapshot';
import { listLibrary } from '@/lib/debate/view';
import { resolveLlm } from '@/lib/ai/provider';
import { apiError, handler } from '@/lib/security/http';
import { isAdmin } from '@/lib/security/admin';
import { THESIS_TOPIC } from '@/lib/topics/topics';

export const dynamic = 'force-dynamic';

/**
 * POST /api/debates (admin only, Authorization: Bearer NEBUBE_ADMIN_TOKEN).
 * Freezes a fresh snapshot and starts a new debate episode. Episodes are otherwise created by
 * the daily refresh when the verdict changes, so visitors never trigger AI spend.
 */
export const POST = handler('debates.create', async (req: Request) => {
  if (!isAdmin(req)) return apiError('forbidden', 'New debate episodes are generated by the scheduled research refresh, not on request.', 403);
  if (!resolveLlm().status.configured) return apiError('ai_unavailable', 'No language model is configured.', 503);
  const { snapshot } = await createSnapshot(THESIS_TOPIC.slug, {});
  const id = await createEpisode(snapshot.id, 'admin request');
  return NextResponse.json({ id, url: `/debates/${id}` }, { status: 202 });
});

/** GET /api/debates?winner=&from=&to=&cursor=&limit= : paginated public episode list. */
export const GET = handler('debates.list', async (req: Request) => {
  const p = new URL(req.url).searchParams;
  const date = (k: string) => {
    const v = p.get(k);
    if (!v || !/^\d{4}-\d{2}-\d{2}$/.test(v)) return undefined;
    return new Date(`${v}T${k === 'to' ? '23:59:59' : '00:00:00'}Z`);
  };
  const cursor = p.get('cursor');
  const r = await listLibrary({
    winner: p.get('winner') ?? undefined, from: date('from'), to: date('to'),
    cursor: cursor && /^d_[A-Za-z0-9_-]{8,20}$/.test(cursor) ? cursor : undefined, limit: Number(p.get('limit') ?? 20) || 20,
  });
  return NextResponse.json(r, { headers: { 'cache-control': 'no-store' } });
});
