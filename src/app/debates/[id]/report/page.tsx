import type { Metadata } from 'next';
import Link from 'next/link';
import { notFound } from 'next/navigation';
import { PrintButton } from '@/components/print-button';
import { ScenarioTable } from '@/components/scenario-table';
import { Container, ExternalLink, Notice, WinnerLabel } from '@/components/ui';
import { buildReport } from '@/lib/debate/report';
import { loadDebateView } from '@/lib/debate/view';
import { formatDate, formatDateTime } from '@/lib/format';
import { validPublicId } from '@/lib/security/http';

export const dynamic = 'force-dynamic';

export async function generateMetadata({ params }: { params: Promise<{ id: string }> }): Promise<Metadata> {
  return { title: `Thesis report ${(await params).id}`, robots: { index: false } };
}

const CLS: Record<string, string> = { SUPPORTED: 'text-mint', CONTRADICTED: 'text-coral', UNKNOWN: 'text-amber', ASSUMPTION: 'text-amber', CONTEXT: 'text-fg-2' };

export default async function ReportPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  if (!validPublicId(id, 'd')) notFound();
  const view = await loadDebateView(id);
  if (!view) notFound();
  if (view.status !== 'COMPLETE') {
    return (
      <Container className="py-16">
        <Notice tone="warn" title="The report is not ready yet.">It is assembled when the debate completes. <Link className="link" href={`/debates/${id}`}>Return to the debate</Link>.</Notice>
      </Container>
    );
  }
  const r = buildReport(view)!;
  const v = r.verdict!;
  return (
    <Container className="max-w-[980px] py-10 md:py-14">
      <div className="no-print mb-8 flex flex-wrap items-center justify-between gap-3 text-sm">
        <Link href={`/debates/${id}`} className="text-muted hover:text-fg">← Back to the debate</Link>
        <div className="flex gap-2">
          <a href={`/api/debates/${id}/report?format=md`} className="btn btn-ghost">Download Markdown</a>
          <a href={`/api/debates/${id}/report`} className="btn btn-ghost">JSON</a>
          <PrintButton />
        </div>
      </div>
      {r.generatedFrom.synthetic && <div className="mb-6"><Notice tone="warn" title="SYNTHETIC TEST RUN">Generated by the local test fixture, not an AI model. Not a research result.</Notice></div>}

      <header className="border-b hairline pb-8">
        <p className="eyebrow">Investment thesis report · {r.topic.label}</p>
        <h1 className="display-m mt-3 text-balance">{r.topic.question}</h1>
        <p className="mt-4 text-sm text-muted">Evidence frozen {formatDateTime(r.generatedFrom.cutoffAt)} · 90-day window to {formatDate(r.generatedFrom.windowEnd)} · snapshot <span className="num">{r.generatedFrom.snapshotId}</span></p>
      </header>

      <section className="grid gap-6 border-b hairline py-8 md:grid-cols-[1fr_1.2fr]">
        <div>
          <p className="eyebrow">Verdict</p>
          <p className="mt-2 text-3xl"><WinnerLabel winner={v.winner} /></p>
          <p className="mt-1 text-sm text-muted">Judge confidence: {v.confidenceLabel} · Bull {v.scores.bull.total} / Bear {v.scores.bear.total}</p>
          <p className="mt-2 text-xs text-muted">Debate argument scores, not an investment rating.</p>
        </div>
        <p className="leading-relaxed text-fg-2">{v.verdictRationale}</p>
      </section>

      <section className="grid gap-8 border-b hairline py-8 md:grid-cols-2">
        {[{ title: 'Supporting arguments (Bull)', list: r.support, hyp: r.topic.bullHypothesis, c: 'border-mint' }, { title: 'Counterarguments (Bear)', list: r.counter, hyp: r.topic.bearHypothesis, c: 'border-coral' }].map((s) => (
          <div key={s.title}>
            <h2 className="text-lg font-[600]">{s.title}</h2>
            <p className={`mt-2 border-l-2 pl-3 text-sm text-muted ${s.c}`}>{s.hyp}</p>
            <ul className="mt-4 space-y-3 text-sm">
              {s.list.map((c) => (
                <li key={c.claimId}>
                  <p className="text-fg-2">{c.text}</p>
                  <p className="mt-0.5 text-xs text-faint"><span className="num">{c.claimId}</span> · {c.nature} · {c.status} · <span className="num">{c.evidenceIds.join(', ') || 'no citation'}</span></p>
                </li>
              ))}
            </ul>
          </div>
        ))}
      </section>

      {r.assumptions.length > 0 && (
        <section className="border-b hairline py-8">
          <h2 className="text-lg font-[600]">Model inputs, assumptions and scenario sensitivity</h2>
          <div className="mt-4 overflow-x-auto">
            <table className="w-full min-w-[560px] text-left text-sm">
              <thead className="text-xs text-muted"><tr><th className="py-2 font-normal">Input</th><th className="py-2 text-right font-normal">Value</th><th className="py-2 pl-4 font-normal">Kind</th><th className="py-2 pl-4 font-normal">Basis</th></tr></thead>
              <tbody>{r.assumptions.map((a) => <tr key={a.input} className="border-t hairline"><td className="py-2">{a.input}</td><td className="num py-2 text-right">{a.value}</td><td className="py-2 pl-4 text-xs">{a.kind}</td><td className="py-2 pl-4 text-xs text-muted">{a.note}</td></tr>)}</tbody>
            </table>
          </div>
          <div className="mt-6"><ScenarioTable scenarios={r.scenarios} todayVolume={typeof r.scenarios.find((s) => s.key === 'base')?.inputs.V === 'number' ? (r.scenarios.find((s) => s.key === 'base')!.inputs.V as number) : null} /></div>
          {v.inputChallenges.length > 0 && (
            <div className="mt-6">
              <p className="eyebrow">Judge challenges to the inputs</p>
              <ul className="mt-2 space-y-1.5 text-sm">{v.inputChallenges.map((c, i) => <li key={i}><span className="num mr-2 text-mint">{c.input}</span>{c.challenge}</li>)}</ul>
            </div>
          )}
        </section>
      )}

      <section className="grid gap-8 border-b hairline py-8 md:grid-cols-2">
        <div>
          <h2 className="text-lg font-[600]">Falsification triggers</h2>
          <ul className="mt-3 list-disc space-y-1.5 pl-5 text-sm text-fg-2">{r.falsification.map((f, i) => <li key={i}>{f}</li>)}</ul>
        </div>
        <div>
          <h2 className="text-lg font-[600]">Uncertainty and unknowns</h2>
          <ul className="mt-3 space-y-2 text-sm">{r.unknowns.length ? r.unknowns.map((u) => <li key={u.evidenceId}><span className="text-fg-2">{u.label}</span><p className="text-xs text-muted">{u.reason}</p></li>) : <li className="text-muted">No unavailable evidence at snapshot time.</li>}</ul>
        </div>
      </section>

      <section className="border-b hairline py-8">
        <h2 className="text-lg font-[600]">Evidence register</h2>
        <p className="mt-1 text-xs text-muted">SUPPORTED: cited by Bull only. CONTRADICTED: cited by Bear only. CONTEXT: cited by both or neither. UNKNOWN: unavailable at snapshot time.</p>
        <div className="mt-4 overflow-x-auto">
          <table className="w-full min-w-[720px] text-left text-xs">
            <thead className="text-muted"><tr><th className="py-2 font-normal">ID</th><th className="py-2 font-normal">Metric</th><th className="py-2 text-right font-normal">Value</th><th className="py-2 pl-3 font-normal">Type</th><th className="py-2 pl-3 font-normal">Register</th><th className="py-2 pl-3 font-normal">Period</th><th className="py-2 pl-3 font-normal">Source</th></tr></thead>
            <tbody>
              {r.evidenceRegister.map((e) => (
                <tr key={e.evidenceId} className="border-t hairline align-top">
                  <td className="num py-2 pr-2 text-faint">{e.evidenceId}</td><td className="py-2 text-fg-2">{e.label}</td><td className="num py-2 text-right">{e.display}</td>
                  <td className="py-2 pl-3">{e.type}</td><td className={`py-2 pl-3 ${CLS[e.classification]}`}>{e.classification}</td><td className="py-2 pl-3 text-muted">{e.period}</td>
                  <td className="py-2 pl-3"><ExternalLink href={e.sourceUrl}>{e.source}</ExternalLink></td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      <section className="py-8">
        <h2 className="text-lg font-[600]">Methodology</h2>
        <ul className="mt-3 list-disc space-y-1.5 pl-5 text-sm text-fg-2">{r.methodology.map((m, i) => <li key={i}>{m}</li>)}</ul>
        <p className="num mt-4 break-all text-[0.6875rem] text-faint">content hash {r.generatedFrom.contentHash} · {r.generatedFrom.methodologyVersion} · {r.generatedFrom.formulaVersion} · {r.generatedFrom.aiModel} · {r.generatedFrom.promptVersion}</p>
      </section>
    </Container>
  );
}
