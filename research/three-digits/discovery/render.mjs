/**
 * Renders research/three-digits/DISCOVERY.md from inventory.json (every number comes from the probe).
 *   node research/three-digits/discovery/render.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const inv = JSON.parse(readFileSync(join(HERE, 'inventory.json'), 'utf8'));
const usd = (v) => (v == null ? 'n/a' : Math.abs(v) >= 1e12 ? `$${(v / 1e12).toFixed(2)}T` : Math.abs(v) >= 1e9 ? `$${(v / 1e9).toFixed(2)}B` : Math.abs(v) >= 1e6 ? `$${(v / 1e6).toFixed(1)}M` : Math.abs(v) >= 1e3 ? `$${(v / 1e3).toFixed(0)}K` : `$${v.toFixed(0)}`);
const span = (x) => (x ? `${x.first} to ${x.last}` : 'none');
const s90 = (x) => (x ? usd(x.sum90) : 'none');
const row = (cells) => `| ${cells.join(' | ')} |`;
const head = (cols) => [row(cols), row(cols.map(() => '---'))].join('\n');
const ok = inv.attempts.filter((a) => a.ok).length;

const assets = inv.assets.map((a) => row([
  `**${a.label}**`, a.type, usd(a.coingecko?.marketCap), s90(a.fees), s90(a.holdersRevenue), a.holdersRevenue ? span(a.holdersRevenue) : 'none', usd(a.tvl), usd(a.stablecoins),
]));
const refs = inv.referenceChains.map((r) => row([r.chain, s90(r.fees), usd(r.tvl), usd(r.stablecoins)]));
const cross = inv.crossChain.map((p) => {
  const vol = p.volumeDex ? `${s90(p.volumeDex)} (${p.volumeDex.category ?? 'DEX overview'}, from ${p.volumeDex.first})` : p.volumeAggregator ? `${s90(p.volumeAggregator)} (bridge-aggregator overview)` : 'not on DefiLlama';
  return row([p.name, vol, p.fees ? `${s90(p.fees)} \`${p.fees.slug}\`` : 'none', s90(p.revenue), s90(p.holdersRevenue)]);
});
const signing = inv.signing.map((p) => row([p.name, p.fees ? `${s90(p.fees)} \`${p.fees.slug}\` (${span(p.fees)})` : 'not on DefiLlama', s90(p.revenue)]));
const ai = inv.ai.map((p) => row([p.name, usd(p.marketCap), p.fees ? s90(p.fees) : 'none', p.revenue ? s90(p.revenue) : 'none', p.volume ? s90(p.volume) : 'none']));
const cats = Object.entries(inv.listings.dexOverviewCategories).sort((a, b) => b[1].total1y - a[1].total1y).slice(0, 8).map(([k, v]) => row([k, String(v.protocols), usd(v.total1y)]));
const failures = inv.attempts.filter((a) => !a.ok && !a.url.includes('/summary/')).map((a) => row([a.note, String(a.status ?? 'network'), (a.error ?? '').replace(/\|/g, '/')]));
const relay = inv.crossChain.find((p) => p.name === 'Relay');
const intents = inv.crossChain.find((p) => p.name === 'NEAR Intents');

const md = `<!-- GENERATED by research/three-digits/discovery/render.mjs from inventory.json. Re-run probe.mjs, then render.mjs. -->

# Discovery: data, coverage and lineage for the comparison universe

SCOPE.md 3.1, sequence item 2. Probe run ${inv.generatedAt.slice(0, 16).replace('T', ' ')} UTC: ${inv.attempts.length} requests, ${ok} returned data. Every attempt, including failures, is in \`inventory.json\`. "90d" is the sum over the last 90 complete days in each series; series end dates can differ here, so this table is an inventory, not a comparison. Comparisons in the thesis re-read the data on a common end date.

## 1. Investable alternatives and platforms

${head(['Asset', 'Valuation method (SCOPE §4)', 'Market cap', 'Chain fees, 90d', 'Holders revenue, 90d', 'Holders revenue coverage', 'DeFi TVL', 'Stablecoins'])}
${assets.join('\n')}

Ethereum-ecosystem references (activity only, no token):

${head(['Chain', 'Fees, 90d', 'DeFi TVL', 'Stablecoins'])}
${refs.join('\n')}

Notes:
- BTC has no holders-revenue series (it has no burn or buyback), as expected for a monetary asset; it is valued with monetary metrics only.
- APT holders revenue starts in 2026-04 on DefiLlama, so its trailing-year multiple is not computable. BNB's series is only BNB Chain's 10% gas burn: BNB's quarterly auto-burn, which removes far more supply, is not in it, so BNB's revenue multiple overstates how little reaches holders. BNB is used in the platform framework only, where this does not enter.
- Hyperliquid's holders revenue is Assistance Fund buybacks (executed onchain purchases); Ethereum, Solana, Tron, Avalanche and NEAR are burns.
- Per-chain DEX volume is not available through the chain summary endpoint for most chains; chain DEX volume comes from the chain-filtered DEX overview (already used for NEAR, Solana, Sui, Avalanche).

## 2. Cross-chain execution (NEAR Intents' market)

DefiLlama's DEX overview, by category (protocols and trailing-year volume):

${head(['Category', 'Protocols', 'Volume, 1 year'])}
${cats.join('\n')}

${head(['Protocol', 'Volume, 90d (where DefiLlama tracks it)', 'Fees, 90d (adapter slug)', 'Revenue, 90d', 'Holders revenue, 90d'])}
${cross.join('\n')}

What this shows about coverage and comparability:
- **Volume is fragmented across three DefiLlama datasets.** NEAR Intents is filed as a "Bridge" inside the DEX overview; Unit (Hyperliquid's spot bridge) is filed with it; THORChain and Chainflip, both cross-chain swap networks, are in the spot "Dexs" category, so they sit inside the spot denominator used by the ladder; LI.FI, Socket and Rango are in the separate bridge-aggregator overview; deBridge, Relay, Across, Mayan, Stargate, Wormhole and Axelar have fee adapters but no volume adapter.
- **The DefiLlama bridges API, which carried bridge volume by protocol, now requires a paid plan** (HTTP 402). Per SCOPE, no paid data is bought until free sources are shown insufficient; alternatives (protocol APIs, Dune public queries) are tried in W2.
- **Fee definitions differ.** Relay's fees include "swap costs" (${s90(relay?.fees)} in 90 days), so they cannot be compared with NEAR Intents' fees (${s90(intents?.fees)}). Revenue is closer to a common definition: Relay ${s90(relay?.revenue)} vs NEAR Intents ${s90(intents?.revenue)} over the same nominal window. Relay is therefore a direct competitor of similar revenue scale whose volume is not on DefiLlama.
- **Revenue that reaches a token is rare in this category.** Across states 0% protocol revenue; Wormhole states no revenue; THORChain's holders revenue is small relative to its revenue.
- **Aggregators sit on top of bridges.** LI.FI, Jumper, Socket and Rango route through the protocols above (and through NEAR Intents), so their volume overlaps and is never added to a category total (SCOPE §7).

## 3. Chain abstraction and signing (Chain Signatures' market)

${head(['Protocol', 'Fees, 90d (slug, coverage)', 'Revenue, 90d'])}
${signing.join('\n')}

Lit Protocol, Particle Network and Squid have no DefiLlama fee adapter. Signing and messaging fees are small across the category on DefiLlama; NEAR's own Chain Signatures fees must be read onchain (v1.signer receipts), which needs BigQuery or NearBlocks exact counts.

## 4. AI agent economy (NEAR AI's market)

${head(['Network', 'Market cap', 'Fees, 90d', 'Revenue, 90d', 'Volume, 90d'])}
${ai.join('\n')}

Public usage and revenue data for AI networks is thin: only Virtuals has a fee adapter, x402 has payment volume, Bittensor's emissions economy is not a fee series. NEAR AI has no public usage, revenue or onchain settlement dataset; it stays SPECULATIVE unless one is found in W3.

## 5. Sources, lineage and access

| Source | Status | Lineage note |
|---|---|---|
| DefiLlama fees, revenue, holders revenue | Public, used | Per-adapter. NEAR chain fees come from Allium; NEAR Intents from Dune queries shared with revenue.near.org, so the two are not independent. |
| DefiLlama DEX and bridge-aggregator overviews | Public, used | Per-adapter; categories assigned by DefiLlama. |
| DefiLlama bridges API | **Paid only (HTTP 402)** | Not used. |
| CoinGecko markets | Public, used | Exchange-sourced prices; supply as reported by projects. |
| NEAR RPC (FastNEAR) | Public, used | Primary. Executed buybacks are reconstructed from the buyback wallet's receipts in W4. |
| NearBlocks | Public, rate-limited | Independent indexer; estimates flagged and excluded. |
| BigQuery \`crypto_near_mainnet_us\` | Needs a Google Cloud project | Primary indexed chain data; required for H7 to H9 at full strength. |
| NEAR Intents Explorer API | Partner JWT, not requested | Operator data; H8 is tested from onchain logs or marked untested. |

${failures.length ? `Failed non-adapter requests:\n\n${head(['Request', 'Status', 'Response'])}\n${failures.join('\n')}\n` : ''}
## 6. Consequences for the workstreams

1. **W2 cross-chain comparison** has to assemble volume from three DefiLlama datasets plus protocol-level sources for Relay, deBridge, Across and Mayan, and compare on revenue (common definition) where volume is missing.
2. **The spot DEX denominator contains cross-chain venues** (THORChain, Chainflip). They are a small part of spot volume; the ladder states the denominator's definition rather than removing them.
3. **Platform comparisons** have holders revenue for every platform except BTC (by design); APT lacks a trailing year, and BNB's series omits its auto-burn.
4. **Signing and AI** have little comparable public revenue data; those products are compared on what is measurable (integrations, usage) and otherwise labelled SPECULATIVE.
`;
writeFileSync(join(HERE, '..', 'DISCOVERY.md'), md);
console.log('wrote DISCOVERY.md');
